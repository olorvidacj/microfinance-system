import { boolean, integer, jsonb, numeric, pgTable, text, timestamp } from 'drizzle-orm/pg-core';

/**
 * The lending service's view of `loans` and `loan_products`. Unlike the
 * declarations in src/db/schema.ts (kept as JS numbers for legacy display
 * code), every amount and rate here stays an exact decimal string, converted
 * with centsFromDb / ppmFromDb from shared/lending.
 */

const money = (name: string) => numeric(name, { precision: 14, scale: 2 });
const rate = (name: string) => numeric(name, { precision: 7, scale: 4 });

export const products = pgTable('loan_products', {
  id: text('id').primaryKey(),
  code: text('code').notNull(),
  name: text('name').notNull(),
  category: text('category').notNull(),
  description: text('description'),
  interestType: text('interest_type').notNull(),
  interestRate: rate('interest_rate').notNull(),
  minAmount: money('min_amount').notNull(),
  maxAmount: money('max_amount').notNull(),
  minTermMonths: integer('min_term_months').notNull(),
  maxTermMonths: integer('max_term_months').notNull(),
  repaymentFrequency: text('repayment_frequency').notNull(),
  fees: jsonb('fees').notNull(),
  latePenaltyRate: rate('late_penalty_rate').notNull(),
  lendingType: text('lending_type').notNull(),
  requiresCollateral: boolean('requires_collateral'),
  requiresGuarantor: boolean('requires_guarantor'),
  status: text('status').notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true, mode: 'string' }),
});

export const loans = pgTable('loans', {
  id: text('id').primaryKey(),
  loanNumber: text('loan_number').notNull(),
  borrowerId: text('borrower_id').notNull(),
  borrowerName: text('borrower_name').notNull(),
  borrowerPhone: text('borrower_phone').notNull(),
  borrowerAvatar: text('borrower_avatar'),
  branchId: text('branch_id').notNull(),
  productId: text('product_id').notNull(),
  productName: text('product_name').notNull(),
  principalAmount: money('principal_amount').notNull(),
  interestRate: rate('interest_rate').notNull(),
  interestType: text('interest_type').notNull(),
  repaymentFrequency: text('repayment_frequency').notNull(),
  termMonths: integer('term_months').notNull(),
  totalInstallments: integer('total_installments').notNull(),
  /** Total of all fees deducted at release. */
  processingFee: money('processing_fee').notNull(),
  totalInterest: money('total_interest').notNull(),
  totalPayable: money('total_payable').notNull(),
  totalPaid: money('total_paid').notNull(),
  remainingBalance: money('remaining_balance').notNull(),
  status: text('status').notNull(),
  coopStep: text('coop_step').notNull(),
  applicationDate: text('application_date').notNull(),
  startDate: text('start_date'),
  approvalDate: text('approval_date'),
  disbursedDate: text('disbursed_date'),
  nextPaymentDate: text('next_payment_date'),
  maturityDate: text('maturity_date').notNull(),
  loanOfficerId: text('loan_officer_id'),
  loanOfficerName: text('loan_officer_name'),
  purpose: text('purpose').notNull(),
  collateral: jsonb('collateral'),
  guarantors: jsonb('guarantors'),
  schedule: jsonb('schedule'),
  underwritingReport: jsonb('underwriting_report'),
  disbursementVoucher: jsonb('disbursement_voucher'),
  disbursementMethod: text('disbursement_method'),
  disbursementAccount: text('disbursement_account'),
  officerInCharge: text('officer_in_charge'),
  lastPaymentDate: text('last_payment_date'),
  daysInArrears: integer('days_in_arrears'),
  fees: jsonb('fees').notNull(),
  netProceeds: money('net_proceeds'),
  installmentAmount: money('installment_amount'),
  penaltyRate: rate('penalty_rate'),
  lendingType: text('lending_type').notNull(),
  /** 0028: the group a GROUP-product loan was taken under. */
  groupId: text('group_id'),
  applicationChannel: text('application_channel'),
  requestKey: text('request_key'),
  createdBy: text('created_by'),
  submittedAt: timestamp('submitted_at', { withTimezone: true, mode: 'string' }),
  reviewedBy: text('reviewed_by'),
  reviewedByName: text('reviewed_by_name'),
  reviewStartedAt: timestamp('review_started_at', { withTimezone: true, mode: 'string' }),
  decidedBy: text('decided_by'),
  decidedByName: text('decided_by_name'),
  decidedAt: timestamp('decided_at', { withTimezone: true, mode: 'string' }),
  decisionReason: text('decision_reason'),
  returnedReason: text('returned_reason'),
  cancellationReason: text('cancellation_reason'),
  closedAt: timestamp('closed_at', { withTimezone: true, mode: 'string' }),
  createdAt: timestamp('created_at', { mode: 'string' }),
  updatedAt: timestamp('updated_at', { withTimezone: true, mode: 'string' }),
});

/** The transaction register (financial_transactions) with an exact amount. */
export const register = pgTable('financial_transactions', {
  id: text('id').primaryKey(),
  referenceNumber: text('reference_number').notNull(),
  clientId: text('client_id').notNull(),
  clientName: text('client_name'),
  accountOrLoanId: text('account_or_loan_id').notNull(),
  accountOrLoanType: text('account_or_loan_type'),
  branchId: text('branch_id'),
  transactionType: text('transaction_type').notNull(),
  amount: money('amount').notNull(),
  transactionDate: text('transaction_date').notNull(),
  paymentMethod: text('payment_method').notNull(),
  processedBy: text('processed_by').notNull(),
  processedByRole: text('processed_by_role'),
  status: text('status').notNull(),
  notes: text('notes'),
  metadata: jsonb('metadata'),
  createdAt: text('created_at').notNull(),
  updatedAt: text('updated_at').notNull(),
});

export type LoanRow = typeof loans.$inferSelect;
export type ProductRow = typeof products.$inferSelect;

/** Posted loan payments (0026). Never deleted; a reversal marks them REVERSED. */
export const paymentRows = pgTable('payments', {
  id: text('id').primaryKey(),
  receiptNumber: text('receipt_number').notNull(),
  loanId: text('loan_id').notNull(),
  loanNumber: text('loan_number').notNull(),
  borrowerId: text('borrower_id').notNull(),
  borrowerName: text('borrower_name').notNull(),
  branchId: text('branch_id').notNull(),
  amount: money('amount').notNull(),
  paymentDate: text('payment_date').notNull(),
  paymentMethod: text('payment_method').notNull(),
  transactionReference: text('transaction_reference').notNull(),
  collectedBy: text('collected_by').notNull(),
  principalPortion: money('principal_portion').notNull(),
  interestPortion: money('interest_portion').notNull(),
  penaltyPortion: money('penalty_portion').notNull(),
  rebateDiscount: money('rebate_discount').notNull(),
  paymentScheduleType: text('payment_schedule_type').notNull(),
  isAdvancePayment: boolean('is_advance_payment'),
  notes: text('notes'),
  createdAt: timestamp('created_at', { mode: 'string' }),
  status: text('status').notNull(),
  paymentKind: text('payment_kind'),
  excessAmount: money('excess_amount').notNull(),
  allocation: jsonb('allocation'),
  idempotencyKey: text('idempotency_key'),
  journalEntryId: text('journal_entry_id'),
  proofId: text('proof_id'),
  postedBy: text('posted_by'),
  postedAt: timestamp('posted_at', { withTimezone: true, mode: 'string' }),
  reversalReference: text('reversal_reference'),
  reversalJournalEntryId: text('reversal_journal_entry_id'),
  reversedAt: timestamp('reversed_at', { withTimezone: true, mode: 'string' }),
  reversedBy: text('reversed_by'),
  reversedByName: text('reversed_by_name'),
  reversalReason: text('reversal_reason'),
});

/** Payment proofs a member uploads (0016), with an exact amount. */
export const proofRows = pgTable('payment_proofs', {
  id: text('id').primaryKey(),
  borrowerId: text('borrower_id').notNull(),
  loanId: text('loan_id').notNull(),
  loanNumber: text('loan_number'),
  amount: money('amount').notNull(),
  currency: text('currency').notNull(),
  paymentMethod: text('payment_method').notNull(),
  paymentDate: text('payment_date').notNull(),
  referenceNumber: text('reference_number'),
  notes: text('notes'),
  documentId: text('document_id'),
  storagePath: text('storage_path'),
  fileName: text('file_name'),
  branchId: text('branch_id').notNull(),
  submittedBy: text('submitted_by'),
  submittedAt: text('submitted_at').notNull(),
  status: text('status').notNull(),
  reviewedBy: text('reviewed_by'),
  reviewedByName: text('reviewed_by_name'),
  reviewedAt: text('reviewed_at'),
  rejectionReason: text('rejection_reason'),
  paymentId: text('payment_id'),
  createdAt: text('created_at').notNull(),
  updatedAt: text('updated_at').notNull(),
});

export type PaymentRow = typeof paymentRows.$inferSelect;
export type ProofRow = typeof proofRows.$inferSelect;
